/**
 * Верифікація того, що мутація СПРАВДІ зачепила рядки.
 *
 * PostgREST під RLS не вважає заблокований запис помилкою: `.delete()` чи
 * `.update()`, які не пройшли політику, повертають **порожній набір і NULL у
 * `error`**. Тобто «видалив» і «не мав права» на дроті виглядають однаково, і
 * клієнт за замовчуванням рапортує успіх.
 *
 * Ціна цієї неоднозначності була не теоретична: `deleteDatabase` і
 * `batchDeleteProperties` спершу стирали файли зі storage, а рядок видаляли
 * ПОТІМ. Заблокований DELETE давав тост «Базу видалено», база лишалась жива —
 * але всі фото вже були знищені безповоротно.
 *
 * Звідси правило, яке тепер тримає весь модуль: **мутація зобовʼязана
 * повернути зачеплені рядки (`.select('id')`) і довести їхню кількість**, а
 * будь-яке знищення файлів іде ЛИШЕ після доведеного видалення рядка.
 */

/** Помилка, яку `humanizeDbError` мапить у зрозуміле «немає доступу». */
export class NoRowsAffectedError extends Error {
  readonly code = '42501'
  constructor(what: string) {
    super(`Немає доступу: ${what}`)
    this.name = 'NoRowsAffectedError'
  }
}

/**
 * Кидає, якщо мутація не зачепила очікувану кількість рядків.
 *
 * @param rows    те, що повернув `.select(...)` після delete/update
 * @param expected скільки рядків мало бути зачеплено
 * @param what    що саме робили — іде в текст помилки
 */
export function assertAffected<T>(
  rows: T[] | null | undefined,
  expected: number,
  what: string,
): T[] {
  const got = rows?.length ?? 0
  // Строга рівність, а не `> 0`: часткове застосування пакетної операції — теж
  // провал, і мовчки лишити половину незміненою гірше, ніж сказати про це.
  if (got !== expected) throw new NoRowsAffectedError(what)
  return rows as T[]
}
