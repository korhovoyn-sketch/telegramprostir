/** Без `'use client'` — з тієї ж причини, що й `i18n.ts`: хелпер кличуть і з
 *  серверних юридичних сторінок. Хуків тут немає, лише побудова вузлів. */
import { Fragment, type ReactNode } from 'react'
import { tr } from './i18n'

/**
 * Переклад речення, ВСЕРЕДИНІ якого стоїть розмітка: `<b>`, `<br/>`,
 * посилання або підставлене значення.
 *
 * ЧОМУ ЦЕ ПОТРІБНО ОКРЕМО. React розбиває такий текст на кілька вузлів, і
 * наївний переклад узяв би кожен уламок як власний ключ: «Ми», «не»,
 * «продаємо ваші дані…». Українською порядок слів це переживає, англійською —
 * ні («We», «not», «sell your data»), тобто речення розсипається саме тим
 * способом, який неможливо помітити по окремому ключу. Ключем мусить бути ЦІЛЕ
 * речення, а місця розмітки — дірками `{0}`, `{1}`.
 *
 *     tx('Буде {0} видалено: усі бази та обʼєкти.', <b>НАЗАВЖДИ</b>)
 *
 * Переклад вільний ставити дірку де завгодно — саме тому порядок слів і
 * лишається природним у кожній мові.
 */
export function tx(key: string, ...nodes: ReactNode[]): ReactNode {
  const parts = tr(key).split(/(\{\d+\})/g)
  return parts.map((p, i) => {
    const m = /^\{(\d+)\}$/.exec(p)
    if (!m) return p
    const node = nodes[Number(m[1])]
    // Дірка без вузла — це розбіжність між ключем і викликом; показати сирий
    // маркер краще, ніж мовчки зʼїсти шматок речення (гард ловить це в тестах).
    return <Fragment key={i}>{node === undefined ? p : node}</Fragment>
  })
}
