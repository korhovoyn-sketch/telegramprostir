/**
 * БЕЗ `'use client'` СВІДОМО. Модуль не має ні хуків, ні доступу до браузера на
 * верхньому рівні, зате його кличуть ОБИДВА середовища: юридичні сторінки
 * `/privacy` і `/terms` — серверні компоненти (експортують `Metadata`), і
 * директива робила виклик `tr()` звідти помилкою збірки
 * («Attempted to call tr() from the server»). Доступ до `localStorage`
 * захищений перевіркою `typeof window` у своїх функціях.
 */
/**
 * ДВОМОВНІСТЬ: КЛЮЧЕМ Є САМ УКРАЇНСЬКИЙ РЯДОК.
 *
 * Це рішення, а не спрощення. Семантичні ключі (`profile.language`) вимагали б
 * вручну зіставити 1097 рядків і НЕ давали б головного: тут `t(s) === s`
 * побайтово, поки мова українська. Тобто наявні 748 тестів — 393 e2e і 355
 * unit, які асертять український текст, — стають гардом УСІЄЇ міграції: якщо
 * кодмод десь помилився, український рендер зсунеться і вони впадуть. З
 * семантичними ключами така помилка була б невидима.
 *
 * Ціна названа чесно: ключі довгі, а зміна українського тексту вимагає правки
 * і виклику, і словника. Гард `i18n.test.ts` це й ловить — осиротілий ключ
 * означає рівно те, що хтось поміняв текст в одному місці з двох.
 *
 * ПІДСТАНОВКИ: `t('Максимум {0} обʼєктів', n)`. Шаблонні рядки з `${}` кодмод
 * перетворює саме так — інакше кожне число породжувало б власний ключ.
 */

/**
 * ЧОМУ ФУНКЦІЯ ЗВЕТЬСЯ `tr`, А НЕ `t`.
 *
 * `t` — галузева конвенція, і саме тому вона тут не годиться: у коді вже є
 * ДВАДЦЯТЬ локальних звʼязувань з таким іменем — ручки `setTimeout`, параметри
 * колбеків, деструктуризовані поля. Кожне з них ЗАТІНИЛО Б імпорт у своїй
 * області видимості.
 *
 * Половину цього ловить компілятор (`Timeout` не викликається), а половину —
 * ні: параметр колбека може виявитись функцією від рядка, і тоді виклик тихо
 * піде не туди. Перейменувати 20 локальних змінних — більший і ризикованіший
 * диф, ніж узяти вільне імʼя тут; `tr` не зустрічається в `src/` як
 * ідентифікатор жодного разу.
 */
export type Lang = 'uk' | 'en'

/** Ключ localStorage. Мова потрібна СИНХРОННО на першому кадрі: інакше
 *  англомовний користувач бачить спалах українського тексту. */
const LANG_KEY = 'ps_lang'

/** Модульний стан, а не React: `t()` кличуть і з хуків, і з `lib/utils.ts`,
 *  і з чистих функцій експорту — місць, де хука немає в принципі. */
let current: Lang = 'uk'
let dict: Record<string, string> = {}

export function getLang(): Lang {
  return current
}

/** Локаль для `toLocaleDateString`/`toLocaleString`. Захардкоджена 'uk-UA'
 *  лишала б англомовному користувачу українські назви місяців і пробіл як
 *  роздільник тисяч — тобто мова перемкнулась би наполовину. */
export function locale(): string {
  return current === 'en' ? 'en-US' : 'uk-UA'
}

/**
 * Переклад. У режимі `uk` повертає ключ БЕЗ жодної обробки — саме це робить
 * український рендер незмінним за побудовою.
 *
 * Відсутній переклад повертає український оригінал: показати користувачу
 * український рядок гірше, ніж англійський, але НЕЗРІВНЯННО краще, ніж
 * порожнє місце або сирий ключ. Прогалини ловить джерельний гард, а не
 * рантайм.
 */
export function tr(uk: string, ...args: (string | number)[]): string {
  const s = current === 'uk' ? uk : (dict[uk] ?? uk)
  if (args.length === 0) return s
  return s.replace(/\{(\d+)\}/g, (m, i) => {
    const v = args[Number(i)]
    return v === undefined ? m : String(v)
  })
}

/**
 * Завантаження словника. Динамічний імпорт СВІДОМО: український користувач —
 * більшість, і платити за англійський словник на холодному старті йому нема
 * за що. Те саме правило, за яким `xlsx` і `jsPDF` не лежать на критичному
 * шляху (див. Performance у CLAUDE.md).
 */
export async function loadLang(lang: Lang): Promise<void> {
  if (lang === 'uk') {
    current = 'uk'
    dict = {}
    return
  }
  // Мова стає активною ЛИШЕ після того, як словник приїхав: інакше перший
  // кадр малює український текст, а другий англійський — блимання гірше за
  // затримку в кілька мілісекунд із кешу.
  const mod = await import('./dict-en')
  dict = mod.EN
  current = 'en'
}

/** Синхронне читання збереженої мови. Доступ до localStorage кидає у
 *  приватному режимі й у превʼю-контекстах — тому try/catch, а не перевірка. */
export function storedLang(): Lang {
  if (typeof window === 'undefined') return 'uk'
  try {
    return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'uk'
  } catch {
    return 'uk'
  }
}

export function persistLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_KEY, lang)
  } catch {
    // Приватний режим — мова просто не переживе перезапуск; профіль у базі
    // лишається джерелом правди на наступному вході.
  }
}
