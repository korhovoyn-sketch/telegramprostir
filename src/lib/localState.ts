'use client'

/**
 * КЛАСИФІКАЦІЯ ЛОКАЛЬНОГО СХОВИЩА: що належить СЕСІЇ, а що ПРИСТРОЮ.
 *
 * Дефект, заради якого це існує: вихід з акаунта чистив рівно один ключ
 * (`ps_user`), а на диску лишались SWR-снапшоти списків — назви обʼєктів,
 * ІМЕНА ОРЕНДАРІВ, ставки, дати договорів, адреси — і чернетки форми.
 * Те саме стосувалось ВИДАЛЕННЯ АКАУНТА, тобто обіцянки §5 Політики
 * конфіденційності про стирання даних.
 *
 * TTL снапшота (24 год) цього не лікує: він робить дані неЧИТАНИМИ для
 * застосунку, але рядок у localStorage лишається назавжди — `readSnapshot`
 * просто повертає null, не видаляючи його.
 *
 * Списки нижче — ЄДИНЕ джерело: з них працює і чистка, і гард
 * `tests/unit/local-storage-hygiene.test.ts`. Новий ключ мусить бути
 * класифікований, інакше гард падає; саме так класифікація не розійдеться
 * з реальністю на першій же фічі.
 */

/** Належить СЕСІЇ: стирається при виході й при видаленні акаунта. */
export const SESSION_PREFIXES = [
  'ps_user',              // кеш профілю: імʼя, tg_id, телефон, роль
  'snap_v',               // SWR-списки баз і обʼєктів (дані орендарів)
  'draft_v',              // чернетка форми обʼєкта
  'ps_guest_join_token',  // гостьовий токен — bearer-креденшл
  'ps:foldCollapse',      // згорнуті папки: містить id бази
] as const

/**
 * Належить ПРИСТРОЮ: переживає вихід СВІДОМО.
 *
 * Критерій один — це НАЛАШТУВАННЯ, а не дані: жоден із цих ключів не
 * розповідає, чий акаунт тут був і що в ньому лежало.
 */
export const DEVICE_KEYS = [
  'ps_lang',        // мова інтерфейсу на цьому пристрої
  'ob_v1',          // які коачмарки вже показані
  'ps:occCompact',  // «Картки / Компактно»
  'kb_h_v1',        // заміряні висоти клавіатури per-геометрія
] as const

/**
 * Чи є зараз активна сесія.
 *
 * ПОТРІБНО ЧЕРЕЗ ГОНКУ, ЯКА ЗВОДИТЬ ЧИСТКУ НАНІВЕЦЬ. Запит списку, випущений
 * ДО натискання «Вийти», резолвиться ПІСЛЯ нього — і його хвіст кличе
 * `writeSnapshot`, повертаючи дані на диск уже після того, як їх стерли.
 * Скасування в завантажувачах немає, а додавати його в кожен — це чотири
 * місця, де достатньо одного гарда на самому записі.
 *
 * Маркером сесії служить `ps_user`: він пишеться РАЗОМ із `setUser` на всіх
 * шляхах входу, тобто існує рівно тоді, коли списки взагалі можуть
 * вантажитись, і зникає першим у `clearSessionState`.
 *
 * Той самий клас, що вже описаний у CLAUDE.md для лічильника сповіщень:
 * виграє не той, хто свіжіший, а той, хто відповів ОСТАННІМ.
 */
export function sessionActive(): boolean {
  if (typeof window === 'undefined') return false
  try { return localStorage.getItem('ps_user') !== null } catch { return false }
}

/** Стирає все, що належить сесії. Викликається з `clearPersistedSession`. */
export function clearSessionState(): void {
  if (typeof window === 'undefined') return
  try {
    const doomed: string[] = []
    for (let i = 0; i < localStorage.length; i++) {
      const k = localStorage.key(i)
      if (k && SESSION_PREFIXES.some((p) => k.startsWith(p))) doomed.push(k)
    }
    // Видалення ЗСУВАЄ індекси, тож збирати й стирати треба окремими проходами.
    doomed.forEach((k) => { try { localStorage.removeItem(k) } catch { /* ignore */ } })
  } catch { /* private mode блокує сховище цілком */ }
}
