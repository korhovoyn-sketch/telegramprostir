import { describe, it, expect } from 'vitest'
import { readFileSync, readdirSync } from 'node:fs'
import { resolve } from 'node:path'

/**
 * ЧОМУ ЦЕЙ ФАЙЛ ІСНУЄ.
 *
 * Політика приватності — це ТВЕРДЖЕННЯ ПРО КОД, і воно вміє розходитись із
 * кодом мовчки: жоден тест ніколи не порівнював їх між собою. Так і сталось.
 * §1 стверджувала, що ми рахуємо «відкриття ваших публічних посилань (БЕЗ
 * ІДЕНТИФІКАЦІЇ відвідувача)» — а міграція 063 і `useViewerActivity` до того
 * часу вже писали `viewer_id`/`viewer_name` і показували глядача ПОІМЕННО
 * («Олена · 8 обʼєктів · сьогодні»). Тобто найчутливіше з можливих тверджень
 * — про ідентифікацію — було хибним, і жодна збірка на це не падала.
 *
 * ЩО ЦЕЙ ГАРД ДОВОДИТЬ, А ЩО НІ. Він доводить, що фіча і речення про неї
 * ІСНУЮТЬ РАЗОМ — не те, що речення правдиве. Правдивість лишається на
 * людині. Але саме співіснування закриває реальний клас: фічу додали, тексту
 * не торкнулись.
 *
 * АНТИВАКУУМ обовʼязковий: якщо маркер зник із коду, вимога «текст його
 * згадує» задовольняється тривіально, і правило тихо стає мертвим. Тому
 * кожен рядок перевіряється З ОБОХ БОКІВ.
 */

const SRC = resolve(process.cwd(), 'src')
const POLICY = resolve(SRC, 'app/privacy/page.tsx')

function walk(dir: string, acc: string[] = []): string[] {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = resolve(dir, e.name)
    if (e.isDirectory()) walk(p, acc)
    else if (/\.tsx?$/.test(e.name)) acc.push(p)
  }
  return acc
}

const policy = readFileSync(POLICY, 'utf8')
const codeFiles = walk(SRC).filter((f) => f !== POLICY)
const code = codeFiles.map((f) => readFileSync(f, 'utf8')).join('\n')

/** маркер у коді → фрагмент, який мусить бути в політиці, і чому саме він */
const CLAIMS: Array<{ marker: RegExp; phrase: string; why: string }> = [
  {
    marker: /\bviewer_name\b/,
    phrase: 'редакторами та підписаними ріелторами',
    why: 'ми зберігаємо ІМʼЯ того, хто відкрив обʼєкт, і показуємо його власнику — '
       + 'це вже не анонімний лічильник, і §1 мусить розрізняти ці два випадки',
  },
  {
    marker: /\blandlord_name\b/,
    phrase: 'орендодавця',
    why: 'імʼя орендодавця — дані ТРЕТЬОЇ особи, введені власником; §1 перелічує '
       + 'такі поля поіменно, бо саме на них тримається пояснення про правові підстави',
  },
  {
    marker: /\bpublic_phone\b/,
    phrase: 'телефон',
    why: 'номер може бути відкритий на публічній сторінці за прапорцем — '
       + 'якщо §1 перестане згадувати телефон, розділ втратить саме той пункт',
  },
]

describe('політика приватності не розходиться з тим, що збирає код', () => {
  for (const { marker, phrase, why } of CLAIMS) {
    it(`${marker.source} → політика це описує`, () => {
      // АНТИВАКУУМ: без фічі вимога до тексту нічого не означає.
      expect(marker.test(code),
        `маркер ${marker.source} зник із src/ — або фічу прибрали (тоді прибери рядок із CLAIMS), `
        + 'або перейменували (тоді онови маркер). Інакше перевірка мовчки стає мертвою')
        .toBe(true)
      expect(policy.includes(phrase),
        `код збирає ${marker.source}, а політика приватності про це не каже: ${why}`)
        .toBe(true)
    })
  }

  /**
   * Окремо — саме те твердження, на якому вже спалились. Зняте формулювання
   * було БЕЗУМОВНИМ («без ідентифікації відвідувача»), тобто читалось як
   * опис УСІХ переглядів, а не лише публічних.
   */
  it('знята безумовна обіцянка анонімності переглядів не повернулась', () => {
    expect(policy).not.toMatch(/публічних посилань \(без ідентифікації/)
  })
})
