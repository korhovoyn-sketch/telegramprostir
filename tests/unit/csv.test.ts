import { describe, it, expect } from 'vitest'
import { parseCsv, detectDelimiter, toCsv, CSV_BOM } from '@/lib/csv'

describe('parseCsv', () => {
  it('розбирає простий файл', () => {
    expect(parseCsv('Назва,Поверх\nОфіс 101,2')).toEqual([['Назва', 'Поверх'], ['Офіс 101', '2']])
  })

  it('лапки ховають роздільник', () => {
    expect(parseCsv('Назва,Адреса\n"Офіс 1","вул. Хрещатик, 1"'))
      .toEqual([['Назва', 'Адреса'], ['Офіс 1', 'вул. Хрещатик, 1']])
  })

  it('подвоєна лапка всередині поля — це одна лапка', () => {
    expect(parseCsv('Назва\n"ТОВ ""Ромашка"""')).toEqual([['Назва'], ['ТОВ "Ромашка"']])
  })

  it('перенос рядка всередині поля не розриває запис', () => {
    expect(parseCsv('Назва,Опис\nОфіс,"перший рядок\nдругий"'))
      .toEqual([['Назва', 'Опис'], ['Офіс', 'перший рядок\nдругий']])
  })

  it('CRLF читається як один кінець рядка', () => {
    expect(parseCsv('a,b\r\n1,2\r\n')).toEqual([['a', 'b'], ['1', '2']])
  })

  // BOM ламає порівняння ПЕРШОГО заголовка, тобто автозіставлення колонок
  // відвалювалось би саме на файлі з Excel — і причину не було б видно ніде.
  it('BOM зрізається, а не їде в перший заголовок', () => {
    expect(parseCsv('﻿Назва,Поверх\nОфіс,2')[0][0]).toBe('Назва')
  })

  it('порожні рядки в кінці файлу відкидаються', () => {
    expect(parseCsv('a\n1\n\n\n')).toEqual([['a'], ['1']])
  })

  it('порожній ввід — порожній результат, а не рядок із однієї клітинки', () => {
    expect(parseCsv('')).toEqual([])
    expect(parseCsv('   \n  ')).toEqual([])
  })
})

describe('detectDelimiter', () => {
  // Українська локаль Excel зберігає CSV з `;` — файл із комами відкривається
  // там одним стовпцем, і навпаки. Без автовизначення половина реальних
  // вивантажень заходила б як єдина колонка.
  it('крапка з комою — українська локаль Excel', () => {
    expect(detectDelimiter('Назва;Поверх;Площа\nОфіс;2;45')).toBe(';')
  })

  it('кома — типовий експорт', () => {
    expect(detectDelimiter('Назва,Поверх\nОфіс,2')).toBe(',')
  })

  it('табуляція теж рахується', () => {
    expect(detectDelimiter('Назва\tПоверх\nОфіс\t2')).toBe('\t')
  })

  // Кома в назві не має переважити справжній роздільник — саме тому рахунок
  // іде ПОЗА лапками.
  it('кома всередині лапок не збиває рахунок', () => {
    expect(detectDelimiter('"Назва, повна";Поверх\n"Офіс, 1";2')).toBe(';')
  })

  it('один стовпець — дефолтна кома, а не випадковий символ', () => {
    expect(detectDelimiter('Назва\nОфіс')).toBe(',')
  })
})

describe('toCsv — друга половина того самого контракту', () => {
  it('поле з роздільником огортається лапками', () => {
    expect(toCsv([['Офіс', 'вул. Хрещатик, 1']])).toBe('Офіс,"вул. Хрещатик, 1"')
  })

  it('лапка всередині подвоюється', () => {
    expect(toCsv([['ТОВ "Ромашка"']])).toBe('"ТОВ ""Ромашка"""')
  })

  it('перенос рядка огортається, а не рве запис', () => {
    expect(toCsv([['a\nb']])).toBe('"a\nb"')
  })

  it('null і undefined стають порожнім полем, а не «null»', () => {
    expect(toCsv([['a', null, undefined, 0]])).toBe('a,,,0')
  })

  // Круговий рейс — єдине, що доводить узгодженість двох половин. Саме тому
  // серіалізатор живе поруч із парсером: у різних файлах вони розійшлись би.
  it('parseCsv(toCsv(x)) повертає x', () => {
    const x = [
      ['Назва', 'Адреса', 'Опис'],
      ['Офіс "А"', 'вул. Хрещатик, 1', 'два\nрядки'],
      ['Офіс Б', '', 'кома, крапка'],
    ]
    expect(parseCsv(toCsv(x))).toEqual(x)
  })

  it('BOM не всередині серіалізатора — інакше рейс був би несиметричним', () => {
    expect(toCsv([['Назва']]).startsWith(CSV_BOM)).toBe(false)
    expect(parseCsv(CSV_BOM + toCsv([['Назва']]))).toEqual([['Назва']])
  })
})
