import { describe, it, expect } from 'vitest'
import { effectiveLandlord, overridesLandlord } from '@/lib/utils'

/**
 * УСПАДКУВАННЯ ОРЕНДОДАВЦЯ: NULL на обʼєкті означає «як у базі».
 *
 * Обидва боки в ОДНОМУ describe свідомо: «обʼєкт перевизначає» саме по собі
 * проходило б і на функції, що завжди віддає значення обʼєкта, а
 * «успадковується» — на тій, що завжди віддає значення бази. Розділені, вони
 * ховали б злам один одного.
 */
describe('effectiveLandlord', () => {
  it('порожній обʼєкт успадковує базу', () =>
    expect(effectiveLandlord(null, 'ТОВ «Дефолт»')).toBe('ТОВ «Дефолт»'))

  it('власне значення обʼєкта ПЕРЕВАЖАЄ базу', () =>
    expect(effectiveLandlord('ФОП Кравець', 'ТОВ «Дефолт»')).toBe('ФОП Кравець'))

  it('обидва порожні — null, а не порожній рядок', () =>
    expect(effectiveLandlord(null, null)).toBeNull())

  it('база порожня, обʼєкт заданий — беремо обʼєкт', () =>
    expect(effectiveLandlord('ФОП Кравець', null)).toBe('ФОП Кравець'))

  // Пробіл у полі не сміє ВИМКНУТИ успадкування: інакше обʼєкт лишився б без
  // орендодавця, хоч у базі він заданий, і жодного сліду причини на екрані.
  it('пробіл на обʼєкті не вимикає успадкування', () =>
    expect(effectiveLandlord('   ', 'ТОВ «Дефолт»')).toBe('ТОВ «Дефолт»'))
})

describe('overridesLandlord — що показувати на картці', () => {
  it('збіг із базою НЕ є перевизначенням', () =>
    expect(overridesLandlord('ТОВ «Дефолт»', 'ТОВ «Дефолт»')).toBe(false))

  it('інше значення — перевизначення', () =>
    expect(overridesLandlord('ФОП Кравець', 'ТОВ «Дефолт»')).toBe(true))

  it('порожній обʼєкт — не перевизначення (успадковує)', () =>
    expect(overridesLandlord(null, 'ТОВ «Дефолт»')).toBe(false))

  // Обʼєкт має орендодавця, база — ні: це теж перевизначення, інакше рядок не
  // показався б ніде, хоч значення унікальне для цього простору.
  it('обʼєкт заданий, база порожня — перевизначення', () =>
    expect(overridesLandlord('ФОП Кравець', null)).toBe(true))
})
