import type { Page } from '@playwright/test'
import { EN } from '../../../src/lib/dict-en'

/**
 * АДАПТЕР ДЛЯ ОБХОДУ АНГЛІЙСЬКОЮ.
 *
 * `helpers/screens.ts` навігує УКРАЇНСЬКИМИ підписами («Меню бази»,
 * «Виділити обʼєкти», /Звільнити/) — і це правильно: то основна мова
 * застосунку. Але англійською ті самі кнопки підписані інакше, тож обхід
 * англійською їх не знайшов би.
 *
 * Друга копія обходу — найгірше з можливих рішень: 25 кроків розійшлися б за
 * раунд, і «англійською все гаразд» перестало б означати те саме, що
 * українською. Тому тут ПРОКСІ над `page`, який перекладає САМ СЕЛЕКТОР тим
 * самим словником, що й інтерфейс. Один адаптер замість двадцяти пʼяти
 * дублікатів.
 */

/**
 * ДАНІ ФІКСТУР, які лишаються українськими НЕЗАЛЕЖНО від мови інтерфейсу:
 * назви баз, обʼєктів, орендарів, імена людей. Перекладати їх у СЕЛЕКТОРІ не
 * можна — обхід шукав би «Office 101» там, де в базі лежить «Офіс 101».
 *
 * Перелік потрібен саме тому, що деякі з цих рядків Є ключами словника:
 * «Офіс 101» — плейсхолдер у формі, тобто законний ключ, і водночас назва
 * тестового обʼєкта. Автоматично ці два вжитки не відрізнити.
 */
export const FIXTURE_DATA = [
  'БЦ Рубін', 'Офіс 101', 'Офіс 102', 'Магазин 1', 'ТОВ «Ромашка»', 'Микола', 'Олена',
  'вул. Хрещатик, 1', 'Хрещатик 22', 'Орендар А', 'Менеджер', 'Гість', 'Прокс',
  'ЖК Перемоги', 'БЦ Олімп', 'Орендар, кв. 5', 'Менеджер Оля', 'Підбірка для клієнта',
  'Офіс 103', 'Перший поверх', 'Фоп Плотко', 'Світлий офіс у центрі міста.',
  'Оля Петренко', 'Оля Редактор', 'Мій орендар', 'Для клієнта А', 'МК', 'К.',
]

/**
 * Ключі з ДІРКАМИ (`Всі ({0})`) прямим пошуком не знайдуться: обхід шукає вже
 * підставлений рядок «Всі (3)». Тому для таких ключів будуємо регекс із
 * захопленням і повертаємо переклад із тими самими значеннями.
 *
 * Наступано: без цього обхід падав на `db-objects` і всьому, що за ним, — а
 * екран при цьому був повністю англійський. Тобто зламаний був ПРИЛАД, і
 * прийняти це за дефект застосунку було б легко.
 */
const TEMPLATES = Object.keys(EN)
  .filter((k) => /\{\d+\}/.test(k))
  // ЗА ПИТОМІСТЮ, спадно. У словнику є ключі-пустушки («{0}{1}», «{0} {1}»),
  // чий регекс `^(.+?)(.+?)$` матчить БУДЬ-ЩО і повертає рядок незміненим.
  // За алфавітом вони йдуть першими, тож без сортування шаблонний пошук
  // мовчки віддавав оригінал — і обхід падав на «Всі (3)», хоч екран був
  // повністю англійський. Прилад ламався переконливіше за застосунок.
  .sort((a, b) => b.replace(/\{\d+\}/g, '').length - a.replace(/\{\d+\}/g, '').length)
  .map((k) => ({
    key: k,
    re: new RegExp('^' + k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\\\{(\d+)\\\}/g, '(.+?)') + '$'),
  }))

function trTemplate(s: string): string | null {
  for (const { key, re } of TEMPLATES) {
    const m = re.exec(s)
    if (!m) continue
    return EN[key].replace(/\{(\d+)\}/g, (_, i) => m[Number(i) + 1] ?? '')
  }
  return null
}

const tr = (s: string) => (FIXTURE_DATA.includes(s) ? s : EN[s] ?? trTemplate(s) ?? s)

/**
 * Регекс-селектори (`/Звільнити/`) перекласти напряму не можна — це фрагмент,
 * а не ключ. Тому шукаємо КЛЮЧІ, які цей регекс матчить, і будуємо
 * альтернативу з їхніх перекладів. Якщо не знайшлось нічого — лишаємо як є:
 * хибний селектор впаде голосно, а тихо підмінений — ні.
 */
function trRegex(re: RegExp): RegExp {
  const hits = Object.keys(EN).filter((k) => !FIXTURE_DATA.includes(k) && re.test(k)).map((k) => EN[k])
  if (!hits.length) return re
  // Дірка `{0}` у перекладі мусить лишитись ПІДСТАНОВОЧНОЮ: інакше з
  // `/Всі \({0}\)/` вийшов би регекс, що шукає літеральні символи «{0}».
  const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\\\{\d+\\\}/g, '.+?')
  return new RegExp([...new Set(hits)].map(esc).join('|'), re.flags.replace('g', ''))
}

type Sel = string | RegExp
const conv = (s: Sel): Sel => (typeof s === 'string' ? tr(s) : trRegex(s))

/**
 * Обгортає `page` так, що всі текстові селектори йдуть через словник.
 * `locator()` і `evaluate()` не чіпаються — вони працюють із класами й DOM,
 * тобто від мови не залежать.
 */
export function enPage(page: Page): Page {
  const wrap = (obj: unknown): unknown =>
    new Proxy(obj as object, {
      get(target, prop, recv) {
        const v = Reflect.get(target, prop, recv)
        if (typeof v !== 'function') return v
        return (...args: unknown[]) => {
          if (prop === 'getByText' || prop === 'getByLabel' || prop === 'getByPlaceholder' || prop === 'getByTitle') {
            args[0] = conv(args[0] as Sel)
          } else if (prop === 'locator' && typeof args[0] === 'string') {
            // CSS-селектор може НЕСТИ ТЕКСТ усередині:
            // `.tabbar [aria-label="Профіль"]`. Проксі бачить його як
            // звичайний рядок, тож перекладаємо саме значення атрибута —
            // інакше обхід шукає українську мітку на англійському екрані.
            args[0] = (args[0] as string).replace(
              /\[aria-label="([^"]+)"\]/g,
              (_, v: string) => `[aria-label="${tr(v)}"]`,
            )
          } else if (prop === 'getByRole' && args[1] && typeof args[1] === 'object') {
            const o = args[1] as { name?: Sel }
            if (o.name !== undefined) args[1] = { ...o, name: conv(o.name) }
          }
          const out = (v as (...a: unknown[]) => unknown).apply(target, args)
          // Локатори теж мусять бути обгорнуті: ланцюг
          // `page.locator('.card').getByText('…')` інакше обійшов би переклад.
          if (out && typeof out === 'object' && 'getByText' in (out as object)) return wrap(out)
          return out
        }
      },
    })
  return wrap(page) as Page
}
